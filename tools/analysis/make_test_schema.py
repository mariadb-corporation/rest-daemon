"""Generate the functional suite's copy of the REST metadata schema.

Reads MariaDB Shell's deployment script from a git ref of the shell repository
(`git show`, never the working tree) and writes it in the form mysqltest runs:

- the `/*<msm:schema_prefix>*/` and `/*<msm:schema_postfix>*/` markers are
  removed (the suite uses the default schema name `mariadb_rest_service`);
- full-line `--` comments become `#` (mysqltest reads `--` as a command);
- the seeded `MariaDB` auth_app is not inserted: the tests create their own
  apps and their results were recorded without it;
- `DELIMITER` lines are kept (mysqltest understands them).

Usage:
  tools/analysis/make_test_schema.py [--shell-repo <dev>/shell] [--ref main]
"""

import argparse
import os
import re
import subprocess
import sys

VERSION = "5.0.0"
SOURCE = ("mysqlshdk/libs/mrs/db_schema/mariadb_rest_service.msm.project/"
          "releases/deployment/mariadb_rest_service_deployment_%s.sql" % VERSION)
TARGET = "tests/mrs/include/schema/mariadb_rest_service-%s.sql" % VERSION

MARKERS = ("/*<msm:schema_prefix>*/", "/*<msm:schema_postfix>*/")

AUTH_APP_START = "-- Default MariaDB auth_app for MariaDB Internal Authentication"
AUTH_APP_NOTE = (
    "# restd: the default 'MariaDB' auth_app is not seeded here: the tests\n"
    "# create their own auth apps and their results were recorded without it\n")


def git(repo, *args):
    return subprocess.run(["git", "-C", repo, *args], check=True,
                          capture_output=True, text=True).stdout


def drop_seeded_auth_app(text):
    start = text.find(AUTH_APP_START)
    if start < 0:
        sys.exit("the seeded auth_app INSERT was not found (%r)" % AUTH_APP_START)
    end = text.find(";\n", start)
    if end < 0 or "INSERT INTO `auth_app`" not in text[start:end]:
        sys.exit("unexpected text after %r" % AUTH_APP_START)
    return text[:start] + AUTH_APP_NOTE + text[end + 2:]


def convert(text):
    for marker in MARKERS:
        text = text.replace(marker, "")
    if "/*<msm:" in text:
        sys.exit("unknown msm marker: %s" %
                 re.search(r"/\*<msm:[^>]*>\*/", text).group(0))
    text = drop_seeded_auth_app(text)
    # full-line SQL comments only: a `--` later in a line is inside a string
    return re.sub(r"^(\s*)--", r"\1#", text, flags=re.M)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--shell-repo", default=os.path.expanduser("<dev>/shell"))
    parser.add_argument("--ref", default="main")
    parser.add_argument("--output", default=None,
                        help="default: %s in this repository" % TARGET)
    args = parser.parse_args()

    commit = git(args.shell_repo, "rev-parse", "--short", args.ref).strip()
    source = git(args.shell_repo, "show", "%s:%s" % (args.ref, SOURCE))

    header = (
        "# restd: MariaDB Shell's deployment script %s (shell %s, %s), made\n"
        "# runnable by mysqltest: the schema prefix/postfix markers removed, the\n"
        "# SQL '--' comments turned into '#' and the seeded 'MariaDB' auth_app\n"
        "# removed (see there). Generated by tools/analysis/make_test_schema.py;\n"
        "# do not edit, regenerate.\n" % (VERSION, args.ref, commit))

    root = os.path.dirname(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__))))
    output = args.output or os.path.join(root, TARGET)
    with open(output, "w", newline="\n") as f:
        f.write(header + convert(source))
    print("wrote %s from %s:%s (%s)" % (output, args.ref, SOURCE, commit))


if __name__ == "__main__":
    main()
